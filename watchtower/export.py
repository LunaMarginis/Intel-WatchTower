"""Machine-readable feeds for other tools. Everything here is deterministic (no 'generated at' stamps in the data files): a day with no new data
leaves the files byte-for-byte unchanged, so the repository does not grow for nothing."""
from __future__ import annotations

import hashlib
import json
import re
import uuid
from datetime import datetime, timedelta

from .parse import Hash, Url, defang_host
from .platforms import platform_of

SIGNATURE = "Generated by Intel WatchTower"
SOURCE_NOTE = "Source: abuse.ch ThreatFox. Entries are community reports, not verified: check before blocking."
NAMESPACE = uuid.UUID("5b0a5a1e-3c7d-4e79-9f0b-8a6d2c1e4f10")  # fixed, so exporting the same hash always gives the same STIX id


def md5_feed(archive: list[Hash], now: datetime, days: int) -> str:
    cut = now - timedelta(days=days)
    hs = sorted((h for h in archive if h.first_seen >= cut), key=lambda h: (h.first_seen, h.ioc_value), reverse=True)
    newest = hs[0].first_seen.strftime("%Y-%m-%d %H:%M UTC") if hs else "n/a"
    head = [f"# MD5 hashes first reported to ThreatFox in the last {days} days: {len(hs)} entries, newest {newest}.", f"# {SOURCE_NOTE}", f"# {SIGNATURE}."]
    return "\n".join(head + [h.ioc_value for h in hs]) + "\n"


def hosts_feed(urls: list[Url]) -> str:
    """Hosts (domains and IPs) that serve malware right now, DEFANGED, one per line. Refang before use."""
    hosts = sorted({u.host for u in urls if u.status == "online" and not platform_of(u.host)})
    head = [f"# Hosts with at least one ONLINE malware URL in URLhaus: {len(hosts)} entries. Defanged: replace [.] with . before use.",
            "# Source: abuse.ch URLhaus. Shared platforms (GitHub, Discord, Dropbox, cloud storage ...) are left out on purpose: see platforms.py.", f"# {SIGNATURE}."]
    return "\n".join(head + [defang_host(h) for h in hosts]) + "\n"


def infra_feed(items: list, kind: str, now: datetime, days: int) -> str:
    """Command-and-control servers (ThreatFox type botnet_cc) first reported in the last `days` days, DEFANGED, one per line."""
    cut = now - timedelta(days=days)
    sel = sorted((i for i in items if i.kind == kind and i.threat_type == "botnet_cc" and i.first_seen >= cut), key=lambda i: (i.first_seen, i.value), reverse=True)
    noun = "domains" if kind == "domain" else "IP addresses"
    head = [f"# ThreatFox command-and-control {noun} first reported in the last {days} days: {len(sel)} entries. Defanged: replace [.] with . before use.",
            "# Community reports, not verified. Check hosting and age before blocking: servers move and addresses are reused.", f"# {SIGNATURE}."]
    return "\n".join(head + [defang_host(i.value) for i in sel]) + "\n"


def _id(kind: str, name: str) -> str:
    return f"{kind}--{uuid.uuid5(NAMESPACE, kind + ':' + name)}"


def _ts(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%dT%H:%M:%S.000Z")


def stix_bundle(archive: list[Hash], now: datetime, days: int = 7) -> dict:
    """A STIX 2.1 bundle: one indicator per MD5 (pattern [file:hashes.MD5 = '…']), one malware object per family, and 'indicates' relationships."""
    cut = now - timedelta(days=days)
    hs = sorted((h for h in archive if h.first_seen >= cut), key=lambda h: (h.first_seen, h.ioc_value))
    identity = _id("identity", "intel-watchtower")
    objects: list[dict] = [{"type": "identity", "spec_version": "2.1", "id": identity, "created": "2026-01-01T00:00:00.000Z", "modified": "2026-01-01T00:00:00.000Z",
                            "name": "Intel WatchTower", "identity_class": "system", "description": SIGNATURE}]
    malware: dict[str, str] = {}
    for h in hs:
        key = h.malware or h.family
        if key not in malware:
            malware[key] = _id("malware", key)
            objects.append({"type": "malware", "spec_version": "2.1", "id": malware[key], "created": _ts(h.first_seen), "modified": _ts(h.first_seen), "created_by_ref": identity,
                            "name": h.family, "is_family": True, **({"aliases": [a.strip() for a in h.alias.split(",") if a.strip()]} if h.alias else {})})
        ind = _id("indicator", h.ioc_value)
        objects.append({"type": "indicator", "spec_version": "2.1", "id": ind, "created": _ts(h.first_seen), "modified": _ts(h.first_seen), "created_by_ref": identity,
                        "name": f"MD5 {h.ioc_value}", "description": f"Reported to ThreatFox as {h.family} ({h.threat_type or 'unknown'}). Not verified. {SIGNATURE}.",
                        "indicator_types": ["malicious-activity"], "pattern": f"[file:hashes.MD5 = '{h.ioc_value}']", "pattern_type": "stix", "valid_from": _ts(h.first_seen),
                        "confidence": max(0, min(100, h.confidence)), "labels": ["threatfox", "unverified"]})
        objects.append({"type": "relationship", "spec_version": "2.1", "id": _id("relationship", h.ioc_value + malware[key]), "created": _ts(h.first_seen), "modified": _ts(h.first_seen),
                        "created_by_ref": identity, "relationship_type": "indicates", "source_ref": ind, "target_ref": malware[key]})
    digest = hashlib.sha1("".join(o["id"] for o in objects).encode()).hexdigest()
    return {"type": "bundle", "id": f"bundle--{uuid.uuid5(NAMESPACE, 'bundle:' + digest)}", "objects": objects}


def stix_text(bundle: dict) -> str:
    return json.dumps(bundle, indent=1, sort_keys=True) + "\n"


def iocs_json(summary: dict) -> str:
    """The numbers behind the README, for dashboards and scripts. `summary` is the run record (see run.py)."""
    return json.dumps(summary, indent=1, sort_keys=True, default=str) + "\n"


# What may leave the private data folder: counts, rankings, trends, health. Every key is listed on purpose; a field added to the state later stays private until it is added here.
PUBLIC_HASHES = ("in_export", "new_this_run", "last24h", "last7", "archive_total", "families_in_export", "window_hours", "newest_age_hours", "confidence", "spark", "daily", "threat_types")
PUBLIC_FAMILY = ("family", "key", "count", "previous", "aliases", "first_seen", "last_seen", "confidence", "daily")
PUBLIC_URLS = ("total", "online", "offline", "online_share", "added_24h", "added_7d", "new_since_last", "bare_ip_share", "bare_ip_online", "unique_hosts", "unique_online_hosts", "unique_domains", "unique_ips",
               "untagged", "window_days", "newest_age_hours", "spark", "daily", "tags", "tags_online", "tag_combos", "risers", "platforms", "platforms_online", "platform_share", "platform_urls", "extensions", "threats")
PUBLIC_INFRA = ("in_export", "new_this_run", "last24h", "last7", "c2_7d", "other_7d", "newest_age_hours", "spark", "daily", "families", "families_c2", "ports", "types")
PUBLIC_RESULT_KEYS = ("name", "status", "detail")


def _pick(src, keys):
    return {k: src[k] for k in keys if k in src}


def public_checks(checks: list[dict]) -> list[dict]:
    """The checks as they may be published: a rejected-row detail ends with an example value from the feed ("e.g. not a domain: …"), which is an indicator: cut it."""
    out = []
    for c in checks:
        c = _pick(c, PUBLIC_RESULT_KEYS)
        c["detail"] = re.split(r",? e\.g\. ", str(c.get("detail", "")), maxsplit=1)[0]
        out.append(c)
    return out


def public_summary(state: dict) -> str:
    """summary.json for the public repository: the numbers behind the public README, with no indicator, host, sample hash, reporter name or feed content."""
    h, u, i = state.get("hashes") or {}, state.get("urls"), state.get("infra")
    out = {"at": state.get("at"), "status": state.get("status"), "version": state.get("version"), "urls_at": state.get("urls_at"), "checks": public_checks(state.get("checks") or []),
           "hashes": {**_pick(h, PUBLIC_HASHES), "families": [_pick(f, PUBLIC_FAMILY) for f in h.get("families", [])]},
           "urls": _pick(u, PUBLIC_URLS) if u else None,
           "infra": ({"domains": _pick(i["domains"], PUBLIC_INFRA) if i.get("domains") else None, "ips": _pick(i["ips"], PUBLIC_INFRA) if i.get("ips") else None, "overlap_total": i.get("overlap_total", 0)} if i else None)}
    return json.dumps(out, indent=1, sort_keys=True, default=str) + "\n"


SAFE = re.compile(r"[^A-Za-z0-9 ._:+/@()#-]")


def safe_text(value: str, limit: int = 60) -> str:
    """Third-party text going into Markdown or Slack: keep a conservative character set (no brackets, backticks, angle brackets, pipes, quotes) and cap the length."""
    return SAFE.sub("", str(value))[:limit].strip() or "unknown"
